"""Turns the team's webcam recordings into frame packs and scenarios, runs them and writes the report.

One command, from the repository root:

  python tools/eval/ingest-recordings.py
  python tools/eval/ingest-recordings.py --recordings DIR --packs DIR --out DIR [runner options]

Recordings are read from ../run/recordings/ next to the repository (--recordings). Each file is named

  <subject>_<condition>_<clip>.<ext>     for example S2_C1_neutral.mp4, S2_C2_blink.mp4, S2_P6_neutral.mp4

  subject    S1..S99, the pseudonym from the paper list (never a name)
  condition  C1..C5 for a genuine recording (lighting, docs/eval/protocol.md section 6), or
             P1..P8 for an attack recording (the species, protocol section 7)
  clip       neutral, blink, smile, turn-left, turn-right, look-up, look-down
  ext        mp4, mov, mkv, webm or avi (landscape; 4:3 or wider)

Steps:

1. Cuts every clip with ffmpeg into a frame pack ``rec-<subject>-<condition>-<clip>`` under the frame-pack root
   (--packs, default $LIVENESS_FRAME_PACKS, else ../run/frame-packs), with the filter and JPEG settings of the
   bona fide packs (crop to 4:3, 640x480, 15 fps).
2. Writes one scenario per subject and condition into <out>/scenarios/: the neutral clip is the main stream, the
   action clips answer the matching prompts, and the challenge pool is limited to the recorded actions, so a
   missing recording never counts as a liveness failure. Genuine groups expect accept, attack groups reject.
   A group needs a neutral clip; a genuine group needs at least two action clips (active.min_challenges is 2);
   an attack group has either none (prompts are ignored, as by a print) or at least two (adaptive replay, P7).
3. Runs tools/eval/scenario-runner/target/scenario-runner.jar (LIVENESS_RUNNER_JAR selects another jar) with
   the shipped configuration, then tools/eval/analyze.py. Unknown options go to the runner unchanged, for
   example --config policy.registration=PASSIVE_THEN_ACTIVE or --threads 1.

Output in --out (default ../run/eval/recordings-<UTC time>): scenarios/, attempts.jsonl, summary.md, run.json,
runner.log, report.md and det.png. Recordings, packs and results stay outside git.
"""

from __future__ import annotations

import argparse
import importlib.util
import os
import re
import subprocess
import sys
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, List, NamedTuple, Tuple

import yaml

import packlib

_EVAL = Path(__file__).resolve().parent
_spec = importlib.util.spec_from_file_location("fetch_frame_packs", _EVAL / "fetch-frame-packs.py")
fetch = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(fetch)

PACK_FILTER = "crop=ih*4/3:ih,scale=640:480,fps=15"  # the recipe filter of the bona fide packs in eval/packs/
ACTIONS = {"blink": "BLINK", "smile": "SMILE", "turn-left": "TURN_LEFT", "turn-right": "TURN_RIGHT",
           "look-up": "LOOK_UP", "look-down": "LOOK_DOWN"}
VIDEO_EXTENSIONS = {".mp4", ".mov", ".mkv", ".webm", ".avi"}
NAME = re.compile(r"^(S\d{1,2})_(C[1-5]|P[1-8])_(neutral|" + "|".join(ACTIONS) + r")$", re.IGNORECASE)
REPEAT = 4
DEFAULT_RECORDINGS = packlib.REPO_ROOT.parent / "run" / "recordings"
DEFAULT_JAR = packlib.REPO_ROOT / "tools" / "eval" / "scenario-runner" / "target" / "scenario-runner.jar"
HEADER = ("# Generated by tools/eval/ingest-recordings.py from the team's webcam recordings (development split).\n"
          "# Frames replayed into the engine: technology regression results, not an ISO/IEC 30107-3 evaluation.\n")


class Clip(NamedTuple):
    """One recording, identified by its file name."""

    path: Path
    subject: str
    condition: str
    clip: str

    @property
    def kind(self) -> str:
        return "bona_fide" if self.condition.startswith("C") else "attack"

    @property
    def pack(self) -> str:
        return f"rec-{self.subject}-{self.condition}-{self.clip}".lower()


def parse_name(path: Path) -> Clip:
    """Reads subject, condition and clip from a recording's file name; raises ValueError for any other name."""
    m = NAME.match(path.stem)
    if path.suffix.lower() not in VIDEO_EXTENSIONS or not m:
        raise ValueError(f"{path.name}: expected <S1..S99>_<C1..C5|P1..P8>_<neutral|{'|'.join(ACTIONS)}>"
                         f" with one of {', '.join(sorted(VIDEO_EXTENSIONS))}")
    return Clip(path, m.group(1).upper(), m.group(2).upper(), m.group(3).lower())


def find_clips(folder: Path) -> Tuple[List[Clip], List[str]]:
    """Returns the recordings in a folder and one error per video file whose name breaks the convention or
    names the same recording as another file (another extension or letter case).

    Files that are not videos (checksums, notes) are ignored."""
    clips, errors, seen = [], [], {}
    for p in sorted(folder.iterdir()):
        if p.is_file() and p.suffix.lower() in VIDEO_EXTENSIONS:
            try:
                c = parse_name(p)
            except ValueError as e:
                errors.append(str(e))
                continue
            if c.pack in seen:
                errors.append(f"{p.name}: the same recording as {seen[c.pack]}; keep one of them")
            else:
                seen[c.pack] = p.name
                clips.append(c)
    return clips, errors


def build_scenarios(clips: List[Clip]) -> Tuple[List[dict], List[str]]:
    """Groups clips by subject and condition into scenario dictionaries; returns them and the skipped groups."""
    groups: Dict[Tuple[str, str], Dict[str, Clip]] = defaultdict(dict)
    for c in clips:
        groups[(c.subject, c.condition)][c.clip] = c
    scenarios, skipped = [], []
    for (subject, condition), by_clip in sorted(groups.items()):
        label = f"{subject}_{condition}"
        if "neutral" not in by_clip:
            skipped.append(f"{label}: no neutral clip")
            continue
        main = by_clip["neutral"]
        actions = {ACTIONS[k]: c.pack for k, c in sorted(by_clip.items()) if k != "neutral"}
        if main.kind == "bona_fide" and len(actions) < 2:
            skipped.append(f"{label}: a genuine group needs at least two action clips, has {len(actions)}")
            continue
        if main.kind == "attack" and len(actions) == 1:
            skipped.append(f"{label}: an attack group needs no action clip or at least two, has 1")
            continue
        s = {"id": f"rec-{'bf' if main.kind == 'bona_fide' else 'atk'}-{subject}-{condition}".lower(),
             "title": f"{subject}, {condition}: team webcam recording", "kind": main.kind}
        if main.kind == "attack":
            s["species"] = condition
        else:
            s["condition"] = condition
        s.update({"subject": subject, "workflow": "registration", "repeat": REPEAT})
        if actions:
            s["config"] = {"active.challenge_types": ",".join(actions)}
            s["stream"] = {"main": main.pack, "actions": actions}
        else:
            s["stream"] = {"main": main.pack}
        s["expect"] = {"outcome": "accept" if main.kind == "bona_fide" else "reject"}
        s["notes"] = "Recordings: " + ", ".join(c.path.name for _, c in sorted(by_clip.items()))
        scenarios.append(s)
    return scenarios, skipped


def write_scenarios(scenarios: List[dict], folder: Path) -> None:
    """Writes each scenario to <folder>/<id>.yaml, after removing the YAML files of an earlier run."""
    folder.mkdir(parents=True, exist_ok=True)
    for old in folder.glob("*.yaml"):
        old.unlink()
    for s in scenarios:
        text = HEADER + yaml.safe_dump(s, sort_keys=False, allow_unicode=True)
        (folder / f"{s['id']}.yaml").write_text(text, encoding="utf-8", newline="\n")


def cut_pack(clip: Clip, root: Path) -> int:
    """Cuts one recording into its frame pack; returns the number of frames."""
    pack = root / clip.pack
    packlib.reset_dir(pack)
    cmd = ["ffmpeg", *fetch.FFMPEG_ARGS, "-i", str(clip.path), "-vf", PACK_FILTER, *fetch.ENCODE_ARGS,
           str(pack / "frame_%05d.jpg")]
    subprocess.run(cmd, check=True)
    return len(list(pack.glob("frame_*.jpg")))


def java() -> str:
    home = os.environ.get("JAVA_HOME")
    return str(Path(home) / "bin" / "java") if home else "java"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--recordings", type=Path, default=DEFAULT_RECORDINGS, help="folder with the recordings")
    ap.add_argument("--packs", type=Path, default=packlib.default_root(), help="frame-pack root to write into")
    ap.add_argument("--out", type=Path, default=None, help="output folder")
    args, runner_args = ap.parse_known_args(argv)
    sys.stdout.reconfigure(line_buffering=True)  # keeps this script's lines in order with the child processes' output
    out = args.out or packlib.REPO_ROOT.parent / "run" / "eval" / (
        "recordings-" + datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ"))
    jar = Path(os.environ.get("LIVENESS_RUNNER_JAR", DEFAULT_JAR))

    for name, folder in (("--out", out), ("--packs", args.packs)):
        resolved = folder.resolve()
        if resolved == packlib.REPO_ROOT or packlib.REPO_ROOT in resolved.parents:
            print(f"{name} {folder} is inside the repository; recordings and results stay outside git",
                  file=sys.stderr)
            return 2
    if not args.recordings.is_dir():
        print(f"no recordings folder: {args.recordings}", file=sys.stderr)
        return 2
    if not jar.is_file():
        print(f"missing {jar}: run mvn -f tools/eval/scenario-runner/pom.xml package", file=sys.stderr)
        return 2
    clips, errors = find_clips(args.recordings)
    for e in errors:
        print("bad file name: " + e, file=sys.stderr)
    if errors:
        return 2
    scenarios, skipped = build_scenarios(clips)
    for s in skipped:
        print("skipped " + s, file=sys.stderr)
    if not scenarios:
        print(f"no usable recordings in {args.recordings}", file=sys.stderr)
        return 2

    used = {p for s in scenarios for p in [s["stream"]["main"], *s["stream"].get("actions", {}).values()]}
    for clip in clips:
        if clip.pack in used:
            try:
                print(f"pack {clip.pack}: {cut_pack(clip, args.packs)} frames from {clip.path.name}")
            except subprocess.CalledProcessError:
                print(f"ffmpeg could not cut {clip.path} (a landscape video is needed)", file=sys.stderr)
                return 2
    write_scenarios(scenarios, out / "scenarios")
    print(f"{len(scenarios)} scenarios in {out / 'scenarios'}")

    out.mkdir(parents=True, exist_ok=True)
    cmd = [java(), "-Xmx512m", "-jar", str(jar), "run", "--packs", str(args.packs), "--scenarios",
           str(out / "scenarios"), "--out", str(out), "--run-id", out.name, "--no-fail", *runner_args]
    with open(out / "runner.log", "w", encoding="utf-8") as log:
        code = subprocess.run(cmd, stdout=log, stderr=subprocess.STDOUT).returncode
    if code != 0:
        print(f"scenario runner failed with exit code {code}; see {out / 'runner.log'}", file=sys.stderr)
        return code
    code = subprocess.run([sys.executable, str(_EVAL / "analyze.py"), str(out / "attempts.jsonl"),
                           "--out", str(out / "report.md")]).returncode
    if code == 0:
        print(f"report: {out / 'report.md'}")
    return code


if __name__ == "__main__":
    sys.exit(main())
